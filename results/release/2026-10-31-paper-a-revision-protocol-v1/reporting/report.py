def main(ev_dir, gen_dir, fig_dir):
    ev, gen = Path(ev_dir), Path(gen_dir)
    S.main(ev_dir, gen_dir, fig_dir)
    split_tables(gen)
    tolerance_cells(gen)
    latex_macros(gen)
    rows = proven_bounds(S.load(ev))
    figure(rows, Path(fig_dir))
    supplement(rows, gen)
    absolute_table(rows, gen)
    import shutil
    rep = ev / "reporting"
    rep.mkdir(exist_ok=True)
    root = Path(__file__).resolve().parents[1]
    shutil.copy2(Path(__file__), rep / "report.py")
    shutil.copy2(root / "VALIDATION_NOTE.md", rep / "VALIDATION_NOTE.md")
    shutil.copy2(root / "EVIDENCE_README.md", ev / "README.md")
    for f in gen.glob("study_*"):
        shutil.copy2(f, rep / f.name)
    shutil.copy2(Path(fig_dir) / "study_evidence.pdf", rep / "study_evidence.pdf")
    print("manifest files:", manifest(ev))


if __name__ == "__main__":
    main(*sys.argv[1:4])
