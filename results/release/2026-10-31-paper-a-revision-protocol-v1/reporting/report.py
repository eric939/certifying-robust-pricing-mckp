def split_tables(gen: Path):
    text = (gen / "study_tables.tex").read_text()
    for block in re.findall(r"\\begin\{table\}.*?\\end\{table\}", text, flags=re.S):
        label = re.search(r"\\label\{([^}]*)\}", block).group(1)
        (gen / TABLE_FILES[label]).write_text("% Generated by study/report.py from study_tables.tex; do not edit.\n"
                                              + block + "\n")


SHORT = {"HR": "HR", "HR-sweep": "HR-sw", "HR-dom": "HR-dom", "HR+BB": "HR+BB", "DNC": "DnC", "MILP": "MILP"}


TOL_EXACT = ("HR+BB", "DNC")
TOL_CELL = r"$\le$1e-4 (tol.)"


def proven_bounds(rows):
    """Exact methods stop with U set to L; the bound they prove is (1+1e-6)L (relative tolerance)."""
    for r in rows:
        if r["method"] in TOL_EXACT and r["status"] == "OPTIMAL" and r.get("objective") is not None:
            L = r["objective"]
            r["bound"] = L + 1e-6 * max(1.0, abs(L))
            r["gap"] = (r["bound"] - L) / r["bound"]
            b = r.get("best_known")
            r["ub_excess"] = (r["bound"] - b) / b if b else None
    return rows


def tolerance_cells(gen: Path):
    """Replace the zero gaps of tolerance-terminated exact methods by the proven tolerance."""
    from study.summarize import METHOD_LABEL
    labs = [METHOD_LABEL[m] for m in TOL_EXACT]
    f = gen / "study_table_panelS.tex"
    out = []
    for line in f.read_text().splitlines():
        c = line.split(" & ")
        if c[0] in labs:
            c[7:10] = [r"\multicolumn{3}{c}{" + TOL_CELL + "}"]
            line = " & ".join(c)
        out.append(line)
    text = "\n".join(out) + "\n"
    text = text.replace(r"Gap uses each method's own bound;",
                        r"Gap uses each method's own bound; tol.: optimal within relative tolerance $10^{-6}$, "
                        r"so the proven bound is $(1+10^{-6})L$ and the gap is at most $10^{-4}\,\%$;")
    f.write_text(text)
    f = gen / "study_table_panelL.tex"
    out = []
    for line in f.read_text().splitlines():
        if any(f"& {lab} &" in line for lab in labs):
            c = line.rsplit(" & ", 2)
            line = c[0] + r" & \multicolumn{2}{c}{" + TOL_CELL + r"}\\"
        out.append(line)
    text = "\n".join(out) + "\n"
    text = text.replace(r"Gap $(U-L)/U$ uses each method's own bound.",
                        r"Gap $(U-L)/U$ uses each method's own bound; tol.\ as in \Cref{tab:panelS-methods}.")
    f.write_text(text)
    f = gen / "study_table_families.tex"
    f.write_text(f.read_text().replace("reported for every instance in the evidence CSV",
                                       "reported for every instance in Online Resource~1"))


def detail_rows(rows, keyf, keys, methods):
    out = []
    for k in keys:
        rs = [r for r in rows if keyf(r) == k]
        for m in methods:
            mr = [r for r in rs if r["method"] == m]
            c = S.status_counts(mr)
            obj = S.q([r.get("exact_revenue") for r in mr if r.get("exact_feasible")])
            out.append((k, m, len(mr), c, obj, S.q([r["deficit"] for r in mr]), S.q([r["ub_excess"] for r in mr]),
                        S.q([r["gap"] for r in mr]), S.q([r["elapsed"] for r in mr if r.get("elapsed") is not None])))
    return out


def supplement(rows, gen: Path):
    head = (r"\documentclass[10pt,a4paper,landscape]{article}" "\n"
            r"\usepackage[margin=1.5cm]{geometry}\usepackage{booktabs,longtable}\usepackage[T1]{fontenc}" "\n"
            r"\newcommand{\Bset}{\mathcal B}" "\n"
            r"\begin{document}" "\n"
            r"\section*{Online Resource 1: per-configuration results of the computational study}" "\n"
            r"Every planned run is included. Done: certified (HullRound variants) or optimal within relative "
            r"tolerance $10^{-6}$; TL: time limit; Inf: infeasible; Fail: error, kill, missing, or a decision "
            r"failing the exact rational check. Objective: exactly verified revenue (median, in units of $10^3$). "
            r"Deficit and UB excess are relative to the best exactly verified revenue of the run; gap is $(U-L)/U$ "
            r"with the method's own bounds. All relative quantities in percent; times in seconds. "
            r"Each entry: median / IQR / maximum. Methods: HR = HullRound (Algorithm 1), HR-sw = guarded sweep, "
            r"HR-dom = sweep with threshold-uniform dominance, HR+BB = HullRound with the exact layer, "
            r"DnC = threshold divide and conquer, MILP = compact formulation solved by HiGHS." "\n"
            r"\scriptsize\setlength{\tabcolsep}{3pt}" "\n")
    cols = (r"\begin{longtable}{llrrrrrr lll}" "\n" r"\toprule" "\n"
            r"Config. & Method & Runs & Done & TL & Inf & Fail & Obj.\ (med) & Deficit (\%) & UB excess (\%) & "
            r"Gap (\%) & Time (s)\\" "\n" r"\midrule\endhead" "\n")
    # fix column spec: 12 columns
    cols = cols.replace(r"{llrrrrrr lll}", r"{llrrrrrrllll}")

    def sfmt(x):
        return ("-" + S.fmt_e(-x)) if x < 0 else S.fmt_e(x)

    def trip(s, f):
        return "--" if s is None else f"{f(s['med'])} / {f(s['q3'] - s['q1'])} / {f(s['max'])}"

    def body(dr, label):
        lines = []
        for (k, m, n, c, obj, de, ub, g, t) in dr:
            lines.append(f"{label(k)} & {SHORT[m]} & {n} & {c['done']} & {c['tl'] + c['tln']} & {c['inf']} & "
                         f"{c['fail']} & {('%.2f' % (obj['med'] / 1e3)) if obj else '--'} & {trip(de, S.fmt_e)} & "
                         f"{trip(ub, sfmt)} & {trip(g, S.fmt_e)} & {trip(t, S.fmt_t)}\\\\")
        return "\n".join(lines)

    Srows = [r for r in rows if r["panel"] == "S"]
    Lrows = [r for r in rows if r["panel"] == "L"]
    keysS = [(g, rad) for g, _ in P.gamma_grid(200) for rad in P.RADII]
    dS = detail_rows(Srows, lambda r: (r["gamma_label"], r["radius"]), keysS, P.METHODS_ALL)
    keysL = [(fam, n, m) for (n, m) in P.PANELS["L"]["sizes"] for fam in P.PANELS["L"]["families"]]
    dL = detail_rows(Lrows, lambda r: (r["family"], r["n"], r["m"]), keysL, P.METHODS_ALL)
    glab = {"0": "0", "sqrt": "sqrt n", "0.1n": "0.1n", "0.5n": "0.5n", "n": "n"}
    doc = [head,
           r"\subsection*{Panel S ($n=200$, $m=16$, 12 runs per configuration: 3 families $\times$ 4 portfolios)}",
           cols + body(dS, lambda k: f"$\\Gamma$={glab[k[0]]}, $\\varrho$={k[1]:.2f}") + "\n"
           r"\bottomrule\end{longtable}",
           r"\subsection*{Panel L ($\Gamma=\lfloor\sqrt n\rfloor$, $\varrho=0.1$, 3 portfolios per configuration; "
           r"configuration = family, $n$, $m$)}",
           cols + body(dL, lambda k: f"{k[0]}, {k[1]}, {k[2]}") + "\n"
           r"\bottomrule\end{longtable}"]
    # per-instance menu statistic
    inst = {}
    for r in rows:
        if r.get("menu_ratio") is not None:
            inst.setdefault(r["base_id"], r)
    lines = [r"\subsection*{Menu statistic $\Delta^v_{\max}/\underline V$ of Corollary 15(a) for every instance}",
             r"\begin{longtable}{llrrrrr}", r"\toprule",
             r"Instance & Family & $n$ & $m$ & $\Delta^v_{\max}$ & $\underline V$ & "
             r"$\Delta^v_{\max}/\underline V$\\", r"\midrule\endhead"]
    for b in sorted(inst):
        r = inst[b]
        lines.append(f"\\texttt{{{b}}} & {S.FAMILY_LABEL[r['family']]} & {r['n']} & {r['m']} & "
                     f"{r['delta_v_max']:.1f} & {r['v_lower']:.4g} & {r['menu_ratio']:.3e}\\\\")
    lines += [r"\bottomrule\end{longtable}", r"\end{document}"]
    doc.append("\n".join(lines))
    (gen / "study_supplement.tex").write_text("% Generated by study/report.py; do not edit.\n" + "\n\n".join(doc) + "\n")


def absolute_table(rows, gen: Path):
    """Absolute objective values and bounds per panel/size and method (added for R1.5)."""
    groups = [("S", None, "Panel S, $n=200$", P.METHODS_ALL)] + [
        ("L", n, f"Panel L, $n={n}$", [m for m in P.METHODS_ALL if m != "HR-dom"])
        for n in sorted({n for (n, _) in P.PANELS["L"]["sizes"]})]

    def k(x):
        return f"{x / 1e3:,.1f}".replace(",", "{,}")

    def a(x):
        return "0" if x == 0 else (f"{x:.2f}" if x < 100 else f"{x:,.0f}".replace(",", "{,}"))

    out = [r"\begin{table}[t]", r"\centering", r"\scriptsize", r"\setlength{\tabcolsep}{4pt}",
           r"\caption{Absolute objective values and bounds (revenue units).  $Z$: exactly verified revenue of "
           r"the returned decision (runs with a decision); $U$: the method's own upper bound (certified bound for "
           r"HullRound, $(1+10^{-6})L$ for the exact layer and DnC, which stop at relative tolerance $10^{-6}$, "
           r"HiGHS's dual bound for the MILP); $U-L$: absolute gap with the method's own lower bound $L$.  "
           r"Medians and ranges are over all runs of the group (Panel~L pools $m\in\{8,16,32\}$ and both "
           r"families, 18 runs per method and $n$); time-limited runs are included with their bounds.  "
           r"Per-configuration values are in Online Resource~1.}",
           r"\label{tab:absolute}",
           r"\begin{tabular}{llrrrrrrr}", r"\toprule",
           r" & & & \multicolumn{3}{c}{$Z$ ($10^3$)} & $U$ ($10^3$) & \multicolumn{2}{c}{$U-L$}\\",
           r"\cmidrule(lr){4-6}\cmidrule(lr){7-7}\cmidrule(lr){8-9}",
           r"Group & Method & Dec. & Med & Min & Max & Med & Med & Max\\", r"\midrule"]
    for gi, (pan, n, lab, methods) in enumerate(groups):
        if gi:
            out.append(r"\addlinespace")
        for j, m in enumerate(methods):
            rs = [r for r in rows if r["panel"] == pan and r["method"] == m and (n is None or r["n"] == n)]
            z = S.q([r["exact_revenue"] for r in rs if r.get("exact_feasible")])
            u = S.q([r["bound"] for r in rs if r.get("bound") is not None])
            g = S.q([r["gap"] * r["bound"] for r in rs if r.get("gap") is not None and r.get("bound") is not None])
            out.append(f"{lab if j == 0 else ''} & {S.METHOD_LABEL[m]} & {z['n'] if z else 0} & "
                       + (f"{k(z['med'])} & {k(z['min'])} & {k(z['max'])}" if z else "-- & -- & --") + " & "
                       + (k(u["med"]) if u else "--") + " & "
                       + (f"{a(g['med'])} & {a(g['max'])}" if g else "-- & --") + r"\\")
    out += [r"\bottomrule", r"\end{tabular}", r"\end{table}"]
    (gen / "study_table_absolute.tex").write_text("% Generated by study/report.py; do not edit.\n"
                                                  + "\n".join(out) + "\n")


def manifest(ev: Path):
    lines = []
    for f in sorted(ev.rglob("*")):
        if f.is_file() and f.name != "MANIFEST.sha256":
            lines.append(f"{hashlib.sha256(f.read_bytes()).hexdigest()}  {f.relative_to(ev)}")
    (ev / "MANIFEST.sha256").write_text("\n".join(lines) + "\n")
    return len(lines)


def latex_macros(gen: Path):
    """Typeset aEb macro values as a\\times10^{b} for running text."""
    text = (gen / "study_macros.tex").read_text()

    def rep(mo):
        mant, ex = mo.group(1), int(mo.group(2))
        if float(mant) == 0:
            return "0"
        return f"\\ensuremath{{{mant}\\times10^{{{ex}}}}}"

    text = re.sub(r"(?<=\{)(\d+(?:\.\d+)?)e([+-]?\d+)(?=\})", rep, text)
    (gen / "study_macros.tex").write_text(text)


