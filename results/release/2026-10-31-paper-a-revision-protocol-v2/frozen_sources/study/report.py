"""Reporting addendum (written after the protocol freeze; changes no run).

Runs the frozen summarizer, splits its tables into one file per table for
the manuscript, writes per-configuration detail tables and the per-instance
menu statistic as a standalone supplementary LaTeX document, and writes the
evidence manifest (SHA-256 of every file in the evidence directory).

Usage: python -m study.report EVIDENCE_DIR GENERATED_DIR FIGURES_DIR
"""
from __future__ import annotations

